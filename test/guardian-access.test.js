const test=require('node:test'),assert=require('node:assert/strict'),policy=require('../server/guardian-access')
test('el jugador normal conserva requisitos; misiones y Arcade ofrecen desbloqueos alternativos',()=>{
 const p={unlocks:[],completedMissions:[],arcadeCompleted:[]}
 assert.equal(Boolean(policy.unlocked("B'atz",{},p,{})),false)
 assert.equal(Boolean(policy.unlocked('Tacuatzin',{},p,{})),false)
 assert.equal(Boolean(policy.unlocked("B'atz",{victorias:10,puntos:500},p,{})),true)
 assert.equal(Boolean(policy.unlocked("B'atz",{victorias:10,puntos:499},p,{})),false)
 assert.equal(Boolean(policy.unlocked("B'atz",{},{...p,completedMissions:['eco-selva','fuego-ancestral']},{})),true)
 assert.equal(Boolean(policy.unlocked('Tacuatzin',{},{...p,arcadeCompleted:['selva','ruinas','volcan']},{})),true)
 assert.equal(Boolean(policy.unlocked('Tacuatzin',{},{...p,arcadeCompleted:['selva','ruinas']},{})),false)
 assert.equal(Boolean(policy.unlocked("B'atz",{},{...p,unlocks:[{type:'mascota',id:"B'atz"}]},{})),true)
 for(const r of policy.RULES)assert.equal(Boolean(policy.unlocked(r.nombre,{},p,{rol:'admin'})),true)
 assert.equal(Boolean(policy.unlocked("B'atz",{},p,{rol:'user',admin:true})),false)
})
test('canje concurrente descuenta una vez, rechaza saldo insuficiente y respeta desafíos y administrador',async t=>{
 const db=require('../db'),{Pool}=require('pg'),{randomUUID}=require('crypto'),pool=new Pool({connectionString:process.env.DATABASE_URL}),id=randomUUID()
 await db.initialize();t.after(async()=>{await pool.query('DELETE FROM accounts WHERE id=$1',[id]);await pool.end();await db.close()})
 await pool.query("INSERT INTO accounts (id,username,display_name,email,password_salt,password_hash,active) VALUES ($1,$2,'Prueba de canjes',$3,'test','test',true)",[id,'unlock_'+id.slice(0,8),id+'@example.test'])
 await assert.rejects(db.redeemGuardian(id,"B'atz"),e=>e.status===409)
 await assert.rejects(db.redeemGuardian(id,'No existe'),e=>e.status===400)
 await pool.query('INSERT INTO player_wallets (account_id,gold) VALUES ($1,1000) ON CONFLICT (account_id) DO UPDATE SET gold=1000',[id])
 const results=await Promise.all([db.redeemGuardian(id,"B'atz"),db.redeemGuardian(id,"B'atz")]);assert.equal(results.reduce((s,r)=>s+r.spent,0),500)
 assert.equal((await db.getAdventureProgress(id)).wallet.gold,500)
 assert.equal((await db.getAdventureProgress(id)).unlocks.filter(u=>u.type==='mascota').length,1)
 await pool.query("INSERT INTO arcade_progress (account_id,level_id) VALUES ($1,'selva'),($1,'ruinas'),($1,'volcan')",[id])
 assert.equal((await db.redeemGuardian(id,'Tacuatzin')).spent,0)
 await pool.query('DELETE FROM arcade_progress WHERE account_id=$1',[id]);await pool.query("UPDATE accounts SET role='admin' WHERE id=$1",[id])
 assert.equal((await db.redeemGuardian(id,'Tacuatzin')).spent,0)
 assert.equal((await db.getAdventureProgress(id)).wallet.gold,500)
})
